package canvas

import (
	"math"
	"testing"
)

func TestParseCoord(t *testing.T) {
	const lat, lon = 48.8566, 2.3522
	// DMS de Paris : 48°51'24"N 2°21'03"E.
	dmsLat, dmsLon := 48+51/60.0+24/3600.0, 2+21/60.0+3/3600.0
	ok := []struct {
		in       string
		lat, lon float64
	}{
		// Décimal.
		{"48.8566, 2.3522", lat, lon},
		{"48.8566,2.3522", lat, lon},
		{"48.8566 , 2.3522", lat, lon},
		{"48,8566;2,3522", lat, lon},
		{"48,8566 ; 2,3522", lat, lon},
		{"48.8566;2.3522", lat, lon},
		{"48.8566 2.3522", lat, lon},
		{"  48.8566\t2.3522  ", lat, lon},
		{"48,8566 2,3522", lat, lon},
		{"48,8566, 2,3522", lat, lon},
		{"48,8566,2,3522", lat, lon},
		{"48.8566|2.3522", lat, lon},
		{"48.8566 / 2.3522", lat, lon},
		{"-33.8688, 151.2093", -33.8688, 151.2093},
		{"-33.8688 151.2093", -33.8688, 151.2093},
		{"40.7128 -74.0060", 40.7128, -74.006},
		{"40.7128, −74.0060", 40.7128, -74.006},
		{"+48.8566 +2.3522", lat, lon},
		{"48 2", 48, 2},
		{"0, 0", 0, 0},
		{"90, 180", 90, 180},
		{"-90, -180", -90, -180},
		// Lettres avant ou après.
		{"48.8566N 2.3522E", lat, lon},
		{"48.8566 N 2.3522 E", lat, lon},
		{"48.8566 N, 2.3522 E", lat, lon},
		{"N48.8566 E2.3522", lat, lon},
		{"N 48.8566, E 2.3522", lat, lon},
		{"40.7128N 74.0060W", 40.7128, -74.006},
		{"40.7128N 74.0060O", 40.7128, -74.006},
		{"40.7128 n 74.0060 w", 40.7128, -74.006},
		{"33.8688S 151.2093E", -33.8688, 151.2093},
		{"S33.8688 E151.2093", -33.8688, 151.2093},
		{"2.3522E 48.8566N", lat, lon},
		{"E 2.3522 N 48.8566", lat, lon},
		{"48,8566N 2,3522E", lat, lon},
		{"48.8566 Nord 2.3522 Est", lat, lon},
		{"40.7128 nord 74.0060 ouest", 40.7128, -74.006},
		// Degrés, minutes, secondes.
		{`48°51'24"N 2°21'03"E`, dmsLat, dmsLon},
		{`48°51'24"N, 2°21'03"E`, dmsLat, dmsLon},
		{`48°51'24"N 2°21'3"E`, dmsLat, dmsLon},
		{`48° 51' 24" N 2° 21' 03" E`, dmsLat, dmsLon},
		{`48°51′24″N 2°21′03″E`, dmsLat, dmsLon},
		{`48° 51′ 24″ N, 2° 21′ 03″ E`, dmsLat, dmsLon},
		{`48º51'24''N 2º21'03''E`, dmsLat, dmsLon},
		{`48°51’24”N 2°21’03”E`, dmsLat, dmsLon},
		{`N 48°51'24" E 2°21'03"`, dmsLat, dmsLon},
		{`N48°51'24" E2°21'03"`, dmsLat, dmsLon},
		{`48°51'24"N 2°21'03"O`, dmsLat, -dmsLon},
		{`48°51'24"N 2°21'03"W`, dmsLat, -dmsLon},
		{`48°51'24" 2°21'03"`, dmsLat, dmsLon},
		{`-33°52'08" 151°12'33"`, -(33 + 52/60.0 + 8/3600.0), 151 + 12/60.0 + 33/3600.0},
		{`48°51'24" -2°21'03"`, dmsLat, -dmsLon},
		{`48°51'24.5"N 2°21'03.25"E`, 48 + 51/60.0 + 24.5/3600, 2 + 21/60.0 + 3.25/3600},
		{`2°21'03"E 48°51'24"N`, dmsLat, dmsLon},
		{"48 51 24 N 2 21 3 E", dmsLat, dmsLon},
		{"48 51 24 2 21 3", dmsLat, dmsLon},
		{`48°N 2°E`, 48, 2},
		// Degrés, minutes décimales.
		{`48°51.4'N 2°21.05'E`, 48 + 51.4/60, 2 + 21.05/60},
		{`48°51,4'N 2°21,05'E`, 48 + 51.4/60, 2 + 21.05/60},
		{`N 48° 51.4' E 2° 21.05'`, 48 + 51.4/60, 2 + 21.05/60},
		{`48°51.4' 2°21.05'`, 48 + 51.4/60, 2 + 21.05/60},
		{"48 51.4 2 21.05", 48 + 51.4/60, 2 + 21.05/60},
		// WKT (longitude d'abord).
		{"POINT(2.3522 48.8566)", lat, lon},
		{"point (2.3522 48.8566)", lat, lon},
		{"POINT ( -74.006 40.7128 )", 40.7128, -74.006},
		{"POINT Z (2.3522 48.8566 35)", lat, lon},
		{"SRID=4326;POINT(2.3522 48.8566)", lat, lon},
		// URI geo.
		{"geo:48.8566,2.3522", lat, lon},
		{"GEO:48.8566,2.3522", lat, lon},
		{"geo:48.8566,2.3522,35", lat, lon},
		{"geo:48.8566,2.3522;u=35", lat, lon},
		{"geo:-33.8688,151.2093?z=12", -33.8688, 151.2093},
	}
	for _, c := range ok {
		la, lo, good := ParseCoord(c.in)
		if !good || math.Abs(la-c.lat) > 1e-9 || math.Abs(lo-c.lon) > 1e-9 {
			t.Errorf("%q : %v %v %v, attendu %v %v", c.in, la, lo, good, c.lat, c.lon)
		}
	}
	bad := []string{
		"", "   ", "Paris", "48.8566", "48.8566, 2.3522, 3", "91, 0", "0, 181", "-90.5 0",
		"48.8566N 2.3522N", "2.35E 48.85E", "48.8566N 2.3522", "N48.8566 2.3522E",
		`48°61'00"N 2°21'03"E`, `48°51'60"N 2°21'03"E`, `48.5°51'N 2°21'E`, `48°51.4'24"N 2°21'03"E`,
		`48°51'24"N 2°21'03"X`, "POINT(2.3522)", "POINT(200 48)", "geo:48.8566", "geo:abc,def",
		"48.8566 2.3522 7", "48 51 24 2 21", `'51 2°`, "48..85 2", "1/2/3",
		`°48 2`, "48°°51 2", "12h30 2",
	}
	for _, s := range bad {
		if la, lo, good := ParseCoord(s); good {
			t.Errorf("%q accepté : %v %v", s, la, lo)
		}
	}
}

func TestParseCoordAxis(t *testing.T) {
	ok := []struct {
		in  string
		lat bool
		v   float64
	}{
		{"48.8566", true, 48.8566},
		{"48,8566", true, 48.8566},
		{" -74,006 ", false, -74.006},
		{"−74.006", false, -74.006},
		{"151.2093", false, 151.2093},
		{"180", false, 180},
		{`48°51'24"N`, true, 48 + 51/60.0 + 24/3600.0},
		{`N 48°51'24"`, true, 48 + 51/60.0 + 24/3600.0},
		{`2°21'03"O`, false, -(2 + 21/60.0 + 3/3600.0)},
		{`2°21,05'E`, false, 2 + 21.05/60},
		{"33.8688 S", true, -33.8688},
		{"48 51 24", true, 48 + 51/60.0 + 24/3600.0},
	}
	for _, c := range ok {
		v, good := ParseCoordAxis(c.in, c.lat)
		if !good || math.Abs(v-c.v) > 1e-9 {
			t.Errorf("%q : %v %v, attendu %v", c.in, v, good, c.v)
		}
	}
	bad := []struct {
		in  string
		lat bool
	}{
		{"", true}, {"abc", true}, {"91", true}, {"181", false}, {"48.85N", false}, {"2.35E", true},
		{"48.8566, 2.3522", true}, {"48 N 2", true}, {"1.000,5", true},
	}
	for _, c := range bad {
		if v, good := ParseCoordAxis(c.in, c.lat); good {
			t.Errorf("%q accepté : %v", c.in, v)
		}
	}
}
